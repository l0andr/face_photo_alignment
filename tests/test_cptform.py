import pytest
import cp2tform
import numpy as np

def test_cp2tform():
    uv = np.array([
        [1.206750610351562,   0.953417236328125],
        [1.646830810546875,   1.046299316406250],
        [1.404457763671875,   1.235964355468750],
        [1.171289062500000,   1.404472412109375],
        [1.511356689453125,   1.483554931640625]
    ])
    xy = np.array([
    [2.011428571428572, 2.468571428571428],
    [3.108571428571429, 2.468571428571428],
    [2.560000000000000, 3.117714285714286],
    [2.066285714285714, 3.708342857142857],
    [3.053714285714286, 3.708342857142857]
    ])
    trans, uv, xy, uv_dev, xy_dev = cp2tform.cp2tform(uv*1000,xy*100)

    expected_transform = np.array([[ 2.62686717e-01, -5.34732827e-02,  0.00000000e+00],
                                [ 5.34732827e-02,  2.62686717e-01,  0.00000000e+00,],
                                [-1.74136104e+02,  6.19357356e+01,  1.00000000e+00]])
    assert np.sum(trans['tdata']['T'] - expected_transform) < 0.0000000001